_client = None


def client():
    """Ленивый клиент: без ключа сюда не доходит ни один вызов."""
    global _client
    if _client is None:
        _client = anthropic.AsyncAnthropic(api_key=config.ANTHROPIC_API_KEY)
    return _client


async def _ask(cards, *, batch_id, niche, city, bot):
    """({номер: (писать, зацепка)}, причина отказа). Одно из двух непустое."""
    try:
        response = await client().messages.create(
            model=MODEL,
            max_tokens=MAX_TOKENS,
            # статичная часть первой и отдельным блоком — иначе кэшировать
            # нечего: карточки в каждом прогоне свои
            system=[{"type": "text", "text": SYSTEM_PROMPT,
                     "cache_control": {"type": "ephemeral"}}],
            # выбор из двух вариантов рассуждений вслух не требует, а мышление
            # съело бы max_tokens; sampling-параметры не передаём, как и везде
            thinking={"type": "disabled"},
            messages=[{"role": "user",
                       "content": user_prompt(cards, niche)}],
        )
    except anthropic.APIError as e:
        log.warning("гейт скаута %s: ошибка API: %s", batch_id, e)
        return {}, f"модель недоступна: {e.__class__.__name__}"

    await _log_cost(response.usage, batch_id=batch_id, niche=niche, city=city,
                    cards=len(cards), bot=bot)
    if getattr(response, "stop_reason", "") == "max_tokens":
        # обрезанный JSON не разберётся, и это не «модель ответила не по
        # формату»: чинится потолком, а не промптом
        log.warning("гейт скаута %s: ответ обрезан на %s карточках", batch_id,
                    len(cards))
        return {}, "ответ обрезан лимитом токенов"
    text = "".join(b.text for b in response.content if b.type == "text").strip()
    try:
        data = json.loads(text)
    except (ValueError, TypeError):
        log.warning("гейт скаута %s: ответ не JSON: %.200s", batch_id, text)
        return {}, "модель ответила не JSON"
    verdicts = _parse(data)
    if not verdicts:
        return {}, "модель ответила не по формату"
    return verdicts, ""


def _parse(data) -> dict[int, tuple[bool, str]]:
    rows = data.get("cards") if isinstance(data, dict) else None
    if not isinstance(rows, list):
        return {}
    verdicts = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("write"), bool):
            continue
        try:
            number = int(row["i"])
        except (KeyError, TypeError, ValueError):
            continue
        hook = row.get("hook")
        hook = hook.strip()[:HOOK_MAX] if isinstance(hook, str) else ""
        verdicts[number] = (row["write"], hook)
    return verdicts


def _apply(cards, verdicts):
    for number, card in enumerate(cards, 1):
        verdict = verdicts.get(number)
        if verdict is None:
            continue  # про карточку модель промолчала — выбрасывать не за что
        card.gate_write, card.gate_hook = verdict


async def _log_cost(usage, *, batch_id, niche, city, cards, bot):
    read = getattr(usage, "cache_read_input_tokens", 0) or 0
    written = getattr(usage, "cache_creation_input_tokens", 0) or 0
    if not read and not written:
        log.info("гейт скаута %s: префикс не закэширован, вход %s токенов",
                 batch_id, usage.input_tokens)
    cost = (
        (Decimal(usage.input_tokens) + Decimal(written) * CACHE_WRITE_RATE
         + Decimal(read) * CACHE_READ_RATE) * PRICE_IN
        + Decimal(usage.output_tokens) * PRICE_OUT
    ) / MILLION
    await costs.log_cost(op=COST_OP, model=MODEL, cost_usd=cost,
                         input_tokens=usage.input_tokens,
                         output_tokens=usage.output_tokens,
                         cache_read_tokens=read, batch_id=batch_id,
                         note=f"гейт {niche} {city}, карточек: {cards}",
                         bot=bot)
