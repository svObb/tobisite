@dataclass(frozen=True)
class GateResult:
    """Итог гейта по пачке. ok=False — решений нет, карточки не тронуты."""
    ok: bool
    kept: int = 0
    dropped: int = 0
    unseen: int = 0
    reason: str = ""
    model: str = MODEL
    prompt_version: str = PROMPT_VERSION


async def run(cards: list, *, batch_id: str, niche: str, city: str,
              bot=None) -> GateResult:
    """Решает по спорным карточкам, стоит ли писать. Заполняет их gate_*."""
    if not cards:
        return GateResult(True)
    if config.SCOUT_GATE_MAX <= 0:
        return GateResult(False, unseen=len(cards),
                          reason="выключен (SCOUT_GATE_MAX=0)")
    if not config.ANTHROPIC_API_KEY:
        return GateResult(False, unseen=len(cards),
                          reason="не задан ANTHROPIC_API_KEY")

    # за потолком карточки остаются нерешёнными: они уедут на модерацию сырыми
    failures = []
    looked = cards[:config.SCOUT_GATE_MAX]
    for start in range(0, len(looked), CHUNK):
        chunk = looked[start:start + CHUNK]
        number = start // CHUNK + 1
        # кэп проверяется перед каждым чанком: его мог исчерпать предыдущий
        if await costs.cap_reached():
            failures.append("месячный кэп расходов на ИИ исчерпан")
            break  # дальше будет то же самое, остальные чанки не спрашиваем
        verdicts, reason = await _ask(chunk, batch_id=batch_id, niche=niche,
                                      city=city, bot=bot)
        if reason:
            # сбойный чанк не отменяет остальные: решения — по карточкам,
            # а не по прогону
            failures.append(f"чанк {number}: {reason}")
            continue
        _apply(chunk, verdicts)
    return GateResult(
        not failures,
        kept=sum(1 for c in cards if c.gate_write is True),
        dropped=sum(1 for c in cards if c.gate_write is False),
        unseen=sum(1 for c in cards if c.gate_write is None),
        reason="; ".join(failures),
    )


def user_prompt(cards: list, niche: str) -> str:
    return (f"<niche>{niche}</niche>\n"
            f"<cards>{json.dumps(payload(cards), ensure_ascii=False)}</cards>\n\n"
            "Реши по каждой карточке. Ответь JSON.")


def payload(cards: list) -> list[dict]:
    """Что видит модель: факты карточки и ничего больше.

    Ни телефона, ни адреса, ни ссылки на источник: номер модели не нужен —
    ей достаточно знать, что он есть, а зацепка с номером телефона внутри была
    бы приглашением его переписать.
    """
    return [
        {"i": n, "name": card.name, "city": card.city or "",
         "score": card.score, "reasons": list(card.reasons),
         "site": normalize_domain(card.website), "ads": bool(card.has_ads)}
        for n, card in enumerate(cards, 1)
    ]


