"""Название товара двумя строками: короткое имя и хвост прайса.

Названия в прайсах магазинов пишутся для склада, а не для витрины:
«Динаміки для ноутбука Dell Latitude E5470 (PK23000RB00 0CGDGM) бу». Одной
строкой такое читается как складская выгрузка — артикул в скобках весит
столько же, сколько сам товар.

Разрез только представление: обе части попадают на страницу, ни один символ
не пропадает, а данные профиля остаются нетронутыми. Резать значение движку
запрещено (см. slots._measure) — здесь и не режется.

Правило разреза одно и оно детерминировано: первая открывающая скобка, а если
по ней головы не выходит — хвостовая пометка состояния («бу», «б/у»). Ни того,
ни другого — название идёт одной строкой, как раньше.
"""
from __future__ import annotations

BRACKETS = "([{"

# Пометка состояния в конце названия. Пишется по-разному, но всегда последним
# словом: «Клавіатура Acer Aspire бу».
TAIL_MARKS = frozenset({"бу", "б/у", "б.у.", "б/в", "used"})

# Голова короче этого — не голова: «TB (Samsung)» это одно название, а не товар
# «TB» с уточнением. Меряется по голове, а не по месту разреза: до скобки может
# стоять и хвост пробелов.
MIN_HEAD = 4


def split_product_name(name) -> tuple[str, str]:
    """(голова, хвост). Пустой хвост — название идёт одной строкой.

    Обе части вместе несут название целиком: ни один символ не теряется и ни
    один не добавляется. Склейка «голова + пробел + хвост» повторяет исходник
    только там, где на месте разреза стоял ровно один пробел; в «Dell(PK123)»
    пробела не было вовсе, и обратно строка собирается без него.

    Скобка стоит раньше пометки, но правом вето не обладает: разрез по ней,
    оставляющий голову короче MIN_HEAD, уступает разрезу по пометке.
    """
    text = str(name).strip()
    for find_cut in (_bracket_cut, _mark_cut):
        cut = find_cut(text)
        if cut is None:
            continue
        head, tail = text[:cut].rstrip(), text[cut:].strip()
        if len(head) >= MIN_HEAD:
            return head, tail
    return text, ""


def _bracket_cut(text: str) -> int | None:
    """Первая открывающая скобка, перед которой уже есть слово."""
    for index, char in enumerate(text):
        if char in BRACKETS and text[:index].strip():
            return index
    return None


def _mark_cut(text: str) -> int | None:
    """Начало хвостовой пометки, если название ею заканчивается.

    Голова, начинающаяся со скобки, — не голова: в «(2 шт) бу» перед пометкой
    стоит количество, а товара в строке нет вовсе.
    """
    head, separator, tail = text.rpartition(" ")
    if not separator or tail.lower() not in TAIL_MARKS:
        return None
    if not head or head[0] in BRACKETS:
        return None
    return len(head) + 1
