import re

import phonenumbers

# Схема в начале строки: http://, https://, любая другая по RFC 3986, а также
# протокол-относительный «//host» — иначе он весь ушёл бы в путь и дал None.
_SCHEME = re.compile(r"^(?:[a-z][a-z0-9+.-]*:)?//")

# Кириллические буквы, неотличимые на вид от латинских. Сайты подменяют ими
# буквы почты, чтобы адрес не собрали спам-боты: глазами он читается, а письмо
# по нему не уходит никуда. Таблица публичная — по ней же site_scrape строит
# свой поиск адресов, иначе поиск и починка разъедутся.
EMAIL_HOMOGLYPHS = {
    "а": "a", "е": "e", "о": "o", "с": "c", "р": "p", "х": "x",
    "і": "i", "ѕ": "s", "у": "y", "ј": "j",
    "А": "A", "Е": "E", "О": "O", "С": "C", "Р": "P", "Х": "X",
    "І": "I", "Ѕ": "S", "У": "Y", "Ј": "J",
    # Двойники только в верхнем регистре: строчные в/к/м/н/т на латиницу
    # не похожи и в таблицу не входят — потому кириллические TLD (.укр, .рф)
    # по-прежнему не раскладываются целиком и ветка IDN не ложносрабатывает.
    "В": "B", "К": "K", "М": "M", "Н": "H", "Т": "T",
}
_HOMOGLYPH_TRANS = str.maketrans(EMAIL_HOMOGLYPHS)


def normalize_domain(url: str | None) -> str | None:
    """URL → голый домен, по которому и ищется дубликат.

    Путь, query и фрагмент отбрасываются намеренно. Раньше они оставались,
    и в базу ложилось shop.example.com/ua — тогда та же компания под адресом
    shop.example.com/ проходила и проверку в форме, и уникальный индекс
    uq_leads_domain_norm_active, то есть дедупликация сайтов не работала
    ни для одного адреса сложнее корня.
    """
    if not url:
        return None
    s = url.strip().lower()
    s = _SCHEME.sub("", s)
    # хост кончается на первом же разделителе: /path, ?query, #fragment
    s = re.split(r"[/?#]", s, maxsplit=1)[0]
    # user:pass@host — учётные данные к домену не относятся
    s = s.rpartition("@")[2]
    if s.startswith("["):
        # IPv6-литерал: двоеточия внутри скобок — часть адреса, а не порт
        host, sep, rest = s.partition("]")
        s = host + sep
    else:
        s = s.split(":", 1)[0]
    if s.startswith("www."):
        s = s[4:]
    return s or None


def normalize_phone(raw: str, region: str | None = None) -> str | None:
    """Телефон → E.164, либо None, если номер не разобрался.

    Фолбэка «оставить одни цифры» здесь сознательно нет. Он давал на выходе
    строку вроде +0501234567, которая никогда не совпадёт с настоящим
    +380501234567, — то есть ровно ломал ту дедупликацию, ради которой поле
    value_norm и заведено. Номер, который phonenumbers не понимает, лучше
    отклонить на вводе и попросить международный формат.
    """
    raw = raw.strip()
    if not raw:
        return None
    try:
        parsed = phonenumbers.parse(raw, region)
    except phonenumbers.NumberParseException:
        return None
    if not phonenumbers.is_valid_number(parsed):
        return None
    return phonenumbers.format_number(parsed, phonenumbers.PhoneNumberFormat.E164)


def normalize_email(raw: str | None) -> str | None:
    """Почта с кириллическими двойниками → латиница. None — адрес непригоден.

    Дефект пришёл с сайта лида: «sаlеs@vortex.dp.ua», где «а» и «е» — U+0430 и
    U+0435. На вид адрес правильный, поэтому он спокойно доехал и до карточки,
    и до mailto на странице клиента, — но письмо по нему не уйдёт, а ссылка
    ведёт в никуда. Отличить подмену можно только по кодам символов, чем эта
    функция и занимается: чинить надо на записи, а не глазами модератора.

    Адрес целиком из ASCII возвращается байт в байт — подменять там нечего.
    Смешанный чинится по таблице EMAIL_HOMOGLYPHS: собралась латиница целиком —
    адрес был обфусцирован, и это его настоящий вид.

    Если латиница не собралась, решает TLD. Не-ASCII после замены — домен в
    национальном алфавите (.укр, .рф), законный IDN, а не обфускация: такой
    адрес не трогаем и не отвергаем, дойдёт ли до него письмо — вопрос проверки
    получателя и линтера аутрича, а не этой функции. ASCII-TLD при кириллице в
    адресе — угадывать чужую почту мы не беремся: None, и путь записи сам
    решает, отвергнуть ввод или пропустить находку.

    Порядок именно такой: TLD «dp.uа» с кириллической «а» — это та же подмена,
    и по одному взгляду на него адрес ушёл бы в IDN нетронутым.
    """
    if not raw:
        return None
    value = raw.strip()
    if value.isascii():
        return raw
    fixed = value.translate(_HOMOGLYPH_TRANS)
    if fixed.isascii():
        return fixed
    tld = fixed.rpartition("@")[2].rpartition(".")[2]
    return raw if tld and not tld.isascii() else None
